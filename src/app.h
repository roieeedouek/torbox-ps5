// TorBox for PS5: shared declarations.
#pragma once
#include <stddef.h>
#include <stdint.h>

#define APP_VERSION "1.0.0"
#define APP_TITLE_ID "PPSA97630"
#define APP_PORT 8080
#define THREAD_STACK (1024 * 1024) // below 2 MiB: titles take bigger stacks from the small flexible pool

// ---- platform (platform.c) ----
void plat_init(void);
void plat_log(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
void plat_notify(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
const char *plat_app_dir(void);        // where the key, the queue and the log live
const char *plat_default_folder(void); // default download folder
const char *plat_mode(void);           // "payload", "title" or "host"
int plat_path_allowed(const char *path); // may the web UI browse/write this path?
void plat_local_ip(char *out, size_t len);
int plat_start_thread(void *(*fn)(void *), void *arg); // detached, THREAD_STACK
int64_t plat_now_ms(void);
void plat_sleep_ms(int ms);

// ---- small string buffer (util.c) ----
typedef struct {
    char *data;
    size_t len, cap;
} sbuf;
void sb_init(sbuf *b);
void sb_free(sbuf *b);
int sb_add(sbuf *b, const void *data, size_t len);
int sb_puts(sbuf *b, const char *s);
int sb_printf(sbuf *b, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
void sb_json_str(sbuf *b, const char *s); // appends a quoted, escaped JSON string
int mkdir_p(const char *path);
void sanitize_name(char *s);              // a safe file name component (also for exFAT)
int sanitize_relpath(const char *in, char *out, size_t len); // "a/b/c" made of sanitized components
int url_decode(char *s);
const char *form_get(const char *form, const char *key, char *out, size_t len); // x-www-form-urlencoded
void url_encode(const char *in, char *out, size_t len);
int sha256_file(const char *path, char hex[65], long long *size); // sha256.c

// ---- minimal JSON reading (json.c) ----
// Finds key in the object that starts at obj (top level of it only); returns a pointer to the value or NULL.
const char *json_find(const char *obj, const char *key);
int json_string(const char *val, char *out, size_t len); // 0 on success
int json_bool(const char *val);                          // 1 true, 0 false, -1 not a bool
long long json_int(const char *val, long long def);

// ---- TorBox API (torbox.c) ----
void tb_init(void);
int tb_have_key(void);
int tb_get_key(char *out, size_t len);
int tb_set_key(const char *key);
void tb_clear_key(void);
const char *tb_key_path(void);
// GET <base>/<path_and_query> with the Bearer key. Returns HTTP status (0 on transport error, err set).
int tb_get(const char *path_and_query, const char *key, sbuf *body, char *err, size_t errlen);
// Requests a download link. kind: "torrents", "webdl", "usenet". file_id < 0 = zip of the item.
int tb_request_link(const char *kind, long long item_id, long long file_id, char *url, size_t urllen, char *err,
                    size_t errlen);
void tb_apply_tls(void *curl_handle); // CA bundle and common options for every curl handle
const char *tb_api_base(void);

// ---- downloads (dl.c) ----
void dl_init(int workers);
// kind: "torrents", "webdl", "usenet" or "url". Returns the job id or -1 (err set).
int dl_add(const char *kind, long long item_id, long long file_id, const char *url, const char *folder,
           const char *subdir, const char *name, char *err, size_t errlen);
void dl_jobs_json(sbuf *out);
int dl_cancel(int id);
int dl_pause(int id);
void dl_settings(int parallel, int connections);
int dl_retry(int id);
int dl_remove(int id);
void dl_clear_finished(void);
void dl_shutdown(void);
int dl_active_count(void);

// ---- web server (httpd.c / api.c) ----
typedef struct {
    int fd;
    char method[8];
    char path[1024];
    char query[4096];
    char *body;
    size_t body_len;
    int has_app_header; // X-TorBox-PS5 present (refuses cross-site form posts)
} http_req;
int httpd_run(int port); // returns when httpd_stop() is called; -1 if the port cannot be bound
void httpd_stop(void);
void http_send(int fd, int status, const char *ctype, const void *body, size_t len, const char *extra_headers);
void http_send_json(int fd, int status, const sbuf *body);
void api_handle(http_req *req);

// ---- embedded files (assets.c, generated by tools/embed.py) ----
typedef struct {
    const char *name;
    const char *ctype;
    const unsigned char *data;
    size_t len;
} asset;
const asset *asset_find(const char *name);
extern const unsigned char cacert_pem[];
extern const size_t cacert_pem_len;
